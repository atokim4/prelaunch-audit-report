import type { Finding } from "../types.ts";
import type { FileEdit } from "./diff.ts";
import { functionArgs, ident, literal, policies, qualify, tableColumns, type SqlFile } from "./sql.ts";

export interface FixContext {
  /** Text of a repo file, or undefined when it does not exist. */
  read(path: string): Promise<string | undefined>;
  /** Every source file path in the repo (relative, forward slashes). */
  files: string[];
  migrations: SqlFile[];
  /** Path for a new migration; unique per call, ordered after the existing ones. */
  newMigration(slug: string): string;
}

export interface PatchDraft {
  edits: FileEdit[];
  summary: string;
  caveats: string[];
}

type Fixer = (finding: Finding, ctx: FixContext) => Promise<PatchDraft | undefined>;

/** The first `backticked` name in the scanner message, normalised. */
function subject(finding: Finding): string | undefined {
  const name = finding.evidence.match(/`([^`]+)`/)?.[1]?.replace(/\(\)$/, "");
  return name;
}

function policyName(finding: Finding): string | undefined {
  return finding.evidence.match(/[Pp]olicy "([^"]+)"/)?.[1];
}

function migration(ctx: FixContext, slug: string, header: string, body: string[]): FileEdit {
  return {
    path: ctx.newMigration(slug),
    after: [`-- ${header}`, "-- Generated by prelaunch-audit. Review before applying.", ...body, ""].join("\n"),
  };
}

const slugOf = (name: string): string => name.replace(/^public\./, "").replace(/[^a-z0-9]+/gi, "_");

const rlsDisabled: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  if (!name) return undefined;
  const table = qualify(name);
  return {
    edits: [
      migration(ctx, `enable_rls_${slugOf(table)}`, `${finding.id}: turn on Row Level Security for ${table}.`, [
        `alter table ${ident(table)} enable row level security;`,
      ]),
    ],
    summary: `Turns on Row Level Security for ${table}. With no policies the public API gets nothing; server code using the service role key keeps working.`,
    caveats: ["If the browser needs to read or write this table, add policies for exactly those rows."],
  };
};

const viewBypassesRls: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  if (!name) return undefined;
  const view = qualify(name);
  return {
    edits: [
      migration(ctx, `security_invoker_${slugOf(view)}`, `${finding.id}: make ${view} respect the caller's RLS.`, [
        `alter view ${ident(view)} set (security_invoker = true);`,
      ]),
    ],
    summary: `Sets security_invoker on ${view}, so the policies of the tables below it apply to whoever queries it.`,
    caveats: ["Needs Postgres 15 or newer (every current Supabase project is)."],
  };
};

const authUsersExposed: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  if (!name) return undefined;
  const view = qualify(name);
  return {
    edits: [
      migration(ctx, `revoke_${slugOf(view)}`, `${finding.id}: take ${view} off the public API.`, [
        `revoke all on ${ident(view)} from anon, authenticated;`,
      ]),
    ],
    summary: `Revokes API access to ${view}, so the account list is no longer readable through /rest/v1/.`,
    caveats: [
      "The feature that used this view stops working. Replace it with a function that checks the caller and returns only what it needs (for example the id for one exact email).",
    ],
  };
};

const definerFunctionAnon: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  if (!name) return undefined;
  const fn = qualify(name);
  const args = functionArgs(ctx.migrations, fn);
  if (args === undefined) return undefined;
  return {
    edits: [
      migration(ctx, `revoke_${slugOf(fn)}`, `${finding.id}: stop the API roles from calling ${fn}().`, [
        `revoke execute on function ${ident(fn)}(${args}) from public, anon, authenticated;`,
      ]),
    ],
    summary: `Revokes execute on ${fn}() from public, anon and authenticated. The service role keeps its own grant, so server code can still call it.`,
    caveats: [
      "Call it only from server code that has checked the user is allowed to (for an admin action: that they are an admin).",
    ],
  };
};

const storagePublicBucket: Fixer = async (finding, ctx) => {
  const bucket = subject(finding);
  if (!bucket) return undefined;
  const open = policies(ctx.migrations, "storage.objects").filter(
    (p) =>
      (p.command === "select" || p.command === "all") &&
      p.using?.includes(`'${bucket}'`) &&
      !/auth\.(uid|jwt)\(\)/.test(p.using),
  );
  return {
    edits: [
      migration(ctx, `private_bucket_${slugOf(bucket)}`, `${finding.id}: make the ${bucket} bucket private.`, [
        `update storage.buckets set public = false where id = ${literal(bucket)};`,
        ...open.map((p) => `drop policy if exists ${ident(p.name)} on storage.objects;`),
      ]),
    ],
    summary: `Makes the ${bucket} bucket private${open.length ? ` and drops ${open.map((p) => `"${p.name}"`).join(", ")}` : ""}. Files stay where they are.`,
    caveats: [
      "Links to these files stop working. Serve them with createSignedUrl() from server code after checking the file belongs to the user.",
    ],
  };
};

/** Columns that tie a row to a user: references auth.users, or the usual owner names. */
function ownerColumns(columns: { name: string; referencesAuthUsers: boolean }[]): string[] {
  const linked = columns.filter((c) => c.referencesAuthUsers).map((c) => c.name);
  if (linked.length) return linked;
  return columns.map((c) => c.name).filter((n) => /^(user_id|owner_id|created_by|author_id)$/.test(n));
}

const permissivePolicy: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  const policy = policyName(finding);
  if (!name || !policy) return undefined;
  const table = qualify(name);
  const existing = policies(ctx.migrations, table).find((p) => p.name === policy);
  const columns = tableColumns(ctx.migrations, table);
  if (!existing || !columns) return undefined;
  const owners = ownerColumns(columns);
  if (!owners.length) return undefined;
  const condition = owners.map((c) => `(select auth.uid()) = ${ident(c)}`).join(" or ");
  const command = existing.command;
  const scoped = `Users can ${command === "all" ? "use" : command} rows they are in`;
  const clause =
    command === "insert"
      ? `with check (${condition})`
      : command === "select" || command === "delete"
        ? `using (${condition})`
        : `using (${condition})\n  with check (${condition})`;
  return {
    edits: [
      migration(ctx, `scope_policy_${slugOf(table)}`, `${finding.id}: limit "${policy}" to the users in the row.`, [
        `drop policy ${ident(policy)} on ${ident(table)};`,
        "",
        `create policy ${ident(scoped)}`,
        `  on ${ident(table)} for ${command}`,
        "  to authenticated",
        `  ${clause};`,
      ]),
    ],
    summary: `Replaces "${policy}" with "${scoped}": signed-in users whose id is in ${owners.join(" or ")}.`,
    caveats: [
      `Check that ${owners.join(" / ")} really is who should have access. If the rows are meant to be public, keep the old policy and say so in a comment.`,
    ],
  };
};

const PRIVILEGED =
  /^(plan|tier|role|roles|is_admin|admin|credits|balance|is_pro|is_premium|is_verified|verified|status|subscription\w*|stripe_\w+)$/;

const updatePrivilegedColumn: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  const policy = policyName(finding);
  if (!name || !policy) return undefined;
  const table = qualify(name);
  const existing = policies(ctx.migrations, table).find((p) => p.name === policy);
  const columns = tableColumns(ctx.migrations, table);
  if (!existing?.using || !columns) return undefined;
  const editable = columns
    .filter((c) => !c.primaryKey && !c.referencesAuthUsers && !PRIVILEGED.test(c.name))
    .filter((c) => !/^(created_at|updated_at|inserted_at)$/.test(c.name))
    .map((c) => c.name);
  const locked = columns.filter((c) => PRIVILEGED.test(c.name)).map((c) => c.name);
  if (!editable.length) return undefined;
  const roles = existing.roles === "public" ? "authenticated" : existing.roles;
  return {
    edits: [
      migration(ctx, `lock_columns_${slugOf(table)}`, `${finding.id}: users may only edit safe columns of ${table}.`, [
        `revoke update on ${ident(table)} from anon, authenticated;`,
        `grant update (${editable.map(ident).join(", ")}) on ${ident(table)} to authenticated;`,
        "",
        `drop policy ${ident(policy)} on ${ident(table)};`,
        "",
        `create policy ${ident(policy)}`,
        `  on ${ident(table)} for update`,
        `  to ${roles}`,
        `  using (${existing.using})`,
        `  with check (${existing.withCheck ?? existing.using});`,
      ]),
    ],
    summary: `Users can update only ${editable.join(", ")}; ${locked.join(", ")} can be changed only by the server. Adds a WITH CHECK to the policy.`,
    caveats: [
      "If the app updates other columns from the browser, add them to the grant. Change paid columns only in server code (for example the Stripe webhook).",
    ],
  };
};

const definerSearchPath: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  if (!name) return undefined;
  const fn = qualify(name);
  const args = functionArgs(ctx.migrations, fn);
  if (args === undefined) return undefined;
  return {
    edits: [
      migration(ctx, `search_path_${slugOf(fn)}`, `${finding.id}: pin the search_path of ${fn}().`, [
        `alter function ${ident(fn)}(${args}) set search_path = '';`,
      ]),
    ],
    summary: `Pins search_path to '' for ${fn}(), so the function only sees the objects it names in full.`,
    caveats: ["Every table and function in the body must be schema-qualified (public.messages, auth.uid())."],
  };
};

/** Replaces one name everywhere it appears in the repo's source and env example files. */
async function renameEverywhere(ctx: FixContext, from: string, to: string): Promise<FileEdit[]> {
  const pattern = new RegExp(String.raw`\b${from}\b`, "g");
  const edits: FileEdit[] = [];
  for (const path of ctx.files) {
    const before = await ctx.read(path);
    if (before === undefined || !pattern.test(before)) continue;
    edits.push({ path, before, after: before.replace(pattern, to) });
  }
  return edits;
}

const publicEnvSecret: Fixer = async (finding, ctx) => {
  const name = subject(finding);
  const prefix = name?.match(/^(NEXT_PUBLIC_|VITE_|EXPO_PUBLIC_)/)?.[1];
  if (!name || !prefix) return undefined;
  const serverName = name.slice(prefix.length);
  const edits = await renameEverywhere(ctx, name, serverName);
  const location = finding.location.kind === "file" ? finding.location.file : undefined;
  const pkg = (await ctx.read("package.json")) ?? "";
  const target = edits.find((e) => e.path === location);
  if (target && /"server-only"/.test(pkg) && !/["']use client["']/.test(target.after)) {
    if (!/import\s+["']server-only["']/.test(target.after)) target.after = `import "server-only";\n${target.after}`;
  }
  if (!edits.length) return undefined;
  return {
    edits,
    summary: `Renames ${name} to ${serverName} in ${edits.map((e) => e.path).join(", ")}${target?.after.startsWith('import "server-only"') ? `, and marks ${location} server-only so a browser import fails the build` : ""}.`,
    caveats: [
      `Rename the variable in your hosting dashboard too, and rotate the key if a build with ${prefix} ever went live.`,
    ],
  };
};

const ANON_KEY_NAMES = ["NEXT_PUBLIC_SUPABASE_ANON_KEY", "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY"];

const serverSecretInClient: Fixer = async (finding, ctx) => {
  if (finding.location.kind !== "file" || subject(finding) !== "SUPABASE_SERVICE_ROLE_KEY") return undefined;
  const path = finding.location.file;
  const before = await ctx.read(path);
  if (!before?.includes("process.env.SUPABASE_SERVICE_ROLE_KEY")) return undefined;
  const env = (await ctx.read(".env.example")) ?? "";
  const anon = ANON_KEY_NAMES.find((n) => env.includes(n)) ?? ANON_KEY_NAMES[0];
  return {
    edits: [{ path, before, after: before.replaceAll("process.env.SUPABASE_SERVICE_ROLE_KEY", `process.env.${anon}`) }],
    summary: `The browser component now uses the public anon key (${anon}), so its queries run under Row Level Security as the signed-in user.`,
    caveats: [
      "The component now sees only the rows its user may see. If it is an admin screen that needs every row, move the query to a route handler that checks the caller is an admin and uses the service role there.",
      "Rotate the service role key if this ever shipped.",
    ],
  };
};

/** `@/lib/stripe` when tsconfig maps @/* to the root, else a relative path. */
function importPath(from: string, to: string, aliasRoot: boolean): string {
  const bare = to.replace(/\.(ts|tsx|js|mjs)$/, "");
  if (aliasRoot) return `@/${bare}`;
  const up = from
    .split("/")
    .slice(0, -1)
    .map(() => "..");
  return [...(up.length ? up : ["."]), bare].join("/");
}

/** A module (other than `self`) that exports a shared `stripe` client. */
async function findStripeModule(ctx: FixContext, self: string): Promise<string | undefined> {
  for (const file of ctx.files) {
    if (!/\.(ts|tsx|js|mjs)$/.test(file) || file === self) continue;
    const text = await ctx.read(file);
    if (text && /export\s+const\s+stripe\s*=\s*new\s+Stripe\(/.test(text)) return file;
  }
  return undefined;
}

/** Adds import lines after the last existing import (or at the top). */
function insertImports(source: string, imports: string[]): string {
  if (!imports.length) return source;
  const last = [...source.matchAll(/^import .*;$/gm)].pop();
  if (!last) return `${imports.join("\n")}\n${source}`;
  const at = (last.index ?? 0) + last[0].length;
  return `${source.slice(0, at)}\n${imports.join("\n")}${source.slice(at)}`;
}

const stripeWebhookUnverified: Fixer = async (finding, ctx) => {
  if (finding.location.kind !== "file") return undefined;
  const path = finding.location.file;
  const before = await ctx.read(path);
  if (!before || !/export\s+async\s+function\s+POST\s*\(/.test(before)) return undefined; // App Router only
  const parse = before.match(
    /^([ \t]*)(?:const|let)\s+(\w+)\s*=\s*\(?\s*await\s+(\w+)\.json\(\)\s*\)?(?:\s+as\s+Stripe\.Event)?\s*;[ \t]*$/m,
  );
  if (!parse) return undefined;
  const [line, indent = "  ", eventVar, requestVar] = parse;

  const stripeModule = await findStripeModule(ctx, path);
  const imports: string[] = [];
  let source = before;
  let stripeRef = "stripe";
  if (stripeModule) {
    const tsconfig = (await ctx.read("tsconfig.json")) ?? "";
    const aliasRoot = /"@\/\*"\s*:\s*\[\s*"\.\/\*"\s*\]/.test(tsconfig);
    imports.push(`import { stripe } from "${importPath(path, stripeModule, aliasRoot)}";`);
    if (!/^import\s+(?:type\s+)?Stripe\s+from\s+"stripe";$/m.test(source))
      imports.push('import type Stripe from "stripe";');
  } else {
    stripeRef = "new Stripe(process.env.STRIPE_SECRET_KEY!)";
    if (/^import\s+type\s+Stripe\s+from\s+"stripe";$/m.test(source)) {
      source = source.replace(/^import\s+type\s+Stripe\s+from\s+"stripe";$/m, 'import Stripe from "stripe";');
    } else if (!/^import\s+Stripe\s+from\s+"stripe";$/m.test(source)) {
      imports.push('import Stripe from "stripe";');
    }
  }
  if (!/import\s*\{[^}]*\bNextResponse\b[^}]*\}\s*from\s*"next\/server"/.test(source)) {
    imports.unshift('import { NextResponse } from "next/server";');
  }
  const i = indent;
  const verified = [
    `${i}const signature = ${requestVar}.headers.get("stripe-signature");`,
    `${i}if (!signature) {`,
    `${i}  return NextResponse.json({ error: "Missing stripe-signature header" }, { status: 400 });`,
    `${i}}`,
    "",
    `${i}let ${eventVar}: Stripe.Event;`,
    `${i}try {`,
    `${i}  ${eventVar} = await ${stripeRef}.webhooks.constructEventAsync(`,
    `${i}    await ${requestVar}.text(),`,
    `${i}    signature,`,
    `${i}    process.env.STRIPE_WEBHOOK_SECRET!,`,
    `${i}  );`,
    `${i}} catch {`,
    `${i}  return NextResponse.json({ error: "Invalid signature" }, { status: 400 });`,
    `${i}}`,
  ].join("\n");
  const after = insertImports(source.replace(line, verified), imports);
  return {
    edits: [{ path, before, after }],
    summary:
      "Reads the raw body and checks the stripe-signature header with constructEventAsync before the handler touches the event. Unsigned or tampered requests get a 400.",
    caveats: [
      "Set STRIPE_WEBHOOK_SECRET to the endpoint's signing secret (whsec_…) in every environment.",
      "Test with `stripe listen --forward-to localhost:3000/api/stripe/webhook` and `stripe trigger checkout.session.completed`.",
    ],
  };
};

